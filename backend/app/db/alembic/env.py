"""Alembic environment.

Alembic owns the application's schema. It deliberately does NOT own the
LangGraph checkpointer's tables: the checkpointer creates those itself via
`.setup()`, so they are filtered out of both autogenerate and reflection here.
Without the filter, the first autogenerated migration run against a database
that has already served a conversation would contain drop_table operations for
schema Alembic never created (CLAUDE.md §6).
"""

from __future__ import annotations

import os
from logging.config import fileConfig
from typing import Any

from alembic import context
from sqlalchemy import create_engine, pool

from app.db.models import Base
from app.db.session import to_sqlalchemy_url

config = context.config
if config.config_file_name is not None:
    # disable_existing_loggers defaults to True, which would switch off the
    # application's own loggers whenever migrations run in-process (tests, or a
    # startup that migrates before serving). Alembic's logging config should
    # configure Alembic, not silence the app.
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata

CHECKPOINTER_TABLES = frozenset(
    {
        "checkpoints",
        "checkpoint_blobs",
        "checkpoint_writes",
        "checkpoint_migrations",
    }
)


def include_name(
    name: str | None, type_: str, parent_names: dict[str, str | None]
) -> bool:
    """Keep the checkpointer's tables out of reflection."""
    return not (type_ == "table" and name in CHECKPOINTER_TABLES)


def include_object(
    object_: Any, name: str | None, type_: str, reflected: bool, compare_to: Any
) -> bool:
    """Keep the checkpointer's tables out of autogenerate comparisons."""
    return not (type_ == "table" and name in CHECKPOINTER_TABLES)


def database_url() -> str:
    """ALEMBIC_DATABASE_URL wins, so tests can migrate the test database.

    Falls back to DATABASE_URL, then to full settings (which also reads the
    repo-root .env). Migrating only needs a connection string, so a bare
    DATABASE_URL is enough — the rest of the service config is not required.
    """
    for variable in ("ALEMBIC_DATABASE_URL", "DATABASE_URL"):
        value = os.environ.get(variable)
        if value:
            return to_sqlalchemy_url(value)

    from app.config import load_settings

    return to_sqlalchemy_url(load_settings().database_url)


def run_migrations_offline() -> None:
    context.configure(
        url=database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        include_name=include_name,
        include_object=include_object,
        compare_type=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    engine = create_engine(database_url(), poolclass=pool.NullPool)
    with engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            include_name=include_name,
            include_object=include_object,
            compare_type=True,
        )
        with context.begin_transaction():
            context.run_migrations()
    engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
